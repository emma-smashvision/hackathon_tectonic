/* KBC_AI=off bunx next dev -p 3813. Real Chrome; local synthetic data only. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.WORLD_UI_URL || 'http://localhost:3813';
let browser;
(async () => {
  fs.mkdirSync('docs/screenshots', { recursive: true });
  browser = await chromium.launch({ headless: true, executablePath: process.env.CHROMIUM_PATH,
    args: ['--enable-webgl', '--ignore-gpu-blocklist'] });
  const context = await browser.newContext({ viewport: { width: 1366, height: 768 }, reducedMotion: 'reduce' });
  const page = await context.newPage();
  page.setDefaultTimeout(45000); page.setDefaultNavigationTimeout(90000);
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  const shot = name => page.screenshot({ path: `docs/screenshots/r2-ui-${name}.png` });
  const panel = () => page.getByTestId('world-panel');
  const rail = () => page.getByRole('navigation', { name: 'World areas', exact: true });
  const state = () => page.evaluate(() => JSON.stringify(Object.fromEntries(Object.entries(localStorage).filter(([k]) => k.startsWith('kbcone.')))));
  const progress = id => page.evaluate(id => JSON.parse(localStorage.getItem(`kbcone.v9.village:${id}`) || 'null'), id);
  async function open(persona) {
    await page.goto(`${base}/dev/world-ui?p=${persona}`, { waitUntil: 'networkidle' });
    await page.locator('[data-world-ready=true]').waitFor();
    await page.getByRole('button', { name: 'Reset world demo', exact: true }).click();
    await page.waitForTimeout(350);
  }
  async function area(name) { await rail().getByRole('button', { name: `${name} · open area`, exact: true }).click(); }
  for (const persona of ['tom', 'karim', 'sofie', 'lina']) {
    await open(persona); await shot(`${persona}-world`);
    assert.equal(await page.getByText('Synthetic demo crowd · not a forecast', { exact: true }).count(), 1);
    const locked = rail().locator('[data-locked=true]');
    assert.ok(await locked.count());
    for (let i = 0; i < await locked.count(); i++) assert.ok((await locked.nth(i).getAttribute('title')).length > 8);
    await area('Home');
    await panel().locator('[data-place-view=home]').waitFor();
    assert.match(await panel().innerText(), /Your demo numbers/);
    assert.doesNotMatch(await panel().innerText(), /\b20\d{2}-\d{2}-\d{2}\b/);
    if (persona === 'karim') assert.match(await panel().innerText(), /€ .* of € .* repaid.*payments/s);
    await shot(`${persona}-home`);
    await page.getByRole('button', { name: 'Close area panel', exact: true }).click();
    await area('Savings'); await panel().getByRole('heading', { name: 'Your accounts', exact: true }).waitFor();
    await shot(`${persona}-savings`);
    await panel().getByRole('button', { name: 'Start lesson', exact: true }).first().click();
    await page.locator('[data-lessonfx-step]').waitFor(); await page.waitForTimeout(650);
    await shot(`${persona}-lesson`);
    assert.equal(await page.getByText('Synthetic demo crowd · not a forecast', { exact: true }).count(), 1);
    await page.getByRole('button', { name: 'Close area panel', exact: true }).click();
  }
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await open('tom');
  const before = await state();
  await rail().getByRole('button', { name: 'Abroad · unlock or explore', exact: true }).click();
  await panel().getByRole('heading', { name: 'A life event', exact: true }).waitFor();
  await shot('tom-unlock-keys');
  await panel().getByRole('button', { name: 'Explore Abroad', exact: true }).click();
  await shot('tom-explore'); assert.equal(await state(), before, 'Explore must not change any saved data');
  await panel().getByRole('button', { name: 'Back to unlock keys', exact: true }).click();
  await panel().getByRole('button', { name: 'This is in my plans', exact: true }).click();
  await panel().getByRole('button', { name: 'Confirm and open Abroad', exact: true }).click();
  await rail().getByRole('button', { name: 'Abroad · open area', exact: true }).waitFor();
  assert.equal((await progress('tom')).unlocks.find(u => u.areaId === 'abroad').key, 'life-event');
  await page.waitForTimeout(900);
  await shot('tom-unlock-cinematic');
  await page.waitForTimeout(2800);
  await shot('tom-abroad-open');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.reload({ waitUntil: 'networkidle' });
  await rail().getByRole('button', { name: 'Abroad · open area', exact: true }).waitFor();
  await rail().getByRole('button', { name: 'Private banking · unlock or explore', exact: true }).click();
  await panel().getByRole('button', { name: 'Set a goal', exact: true }).click();
  await panel().getByLabel('Your goal amount (€)').fill('1');
  await panel().getByRole('button', { name: 'Save goal and open Private banking', exact: true }).click();
  await rail().getByRole('button', { name: 'Private banking · open area', exact: true }).waitFor();
  assert.equal((await progress('tom')).unlocks.find(u => u.areaId === 'private-banking').goal.target, 1);
  await shot('tom-one-euro-goal');
  await open('tom'); await area('Savings');
  const moveForm = panel().locator('form').filter({ has: page.getByRole('heading', { name: 'Move € to a goal', exact: true }) });
  const beforeMove = await panel().innerText();
  await moveForm.locator('input').fill('50');
  await moveForm.getByRole('button', { name: /Move/ }).click();
  await panel().getByText(/moved in this demo/).waitFor();
  assert.notEqual(await panel().innerText(), beforeMove);
  await shot('tom-demo-goal-move');
  await page.getByRole('button', { name: 'Close area panel', exact: true }).click();
  await page.getByRole('button', { name: 'Prepare this area', exact: true }).click();
  await page.waitForTimeout(650);
  const stormFigure = panel().locator('[data-storm-houses]');
  const figureBox = await stormFigure.boundingBox();
  const captionBox = await stormFigure.locator('figcaption').boundingBox();
  assert.ok(figureBox && captionBox && captionBox.y + captionBox.height <= figureBox.y + figureBox.height, 'Storm crowd caption is not clipped');
  await shot('tom-storm');
  await panel().getByRole('button', { name: 'Learn how to prepare', exact: true }).click();
  await page.locator('[data-lessonfx-step]').waitFor(); await page.waitForTimeout(650);
  await shot('tom-lesson-guess');
  for (let i = 0; i < 8; i++) {
    const step = await page.locator('[data-lessonfx-step]').getAttribute('data-lessonfx-step');
    if (step === 'apply') break;
    if (['reveal', 'helped', 'note'].includes(step)) await shot(`tom-lesson-${step}`);
    await panel().getByRole('button', { name: /^(Let the crowd arrive|Explore both horizons|Meet the crowd|See what helped|Read the note|Try it yourself)$/ }).click();
    await page.waitForFunction(previous => document.querySelector('[data-lessonfx-step]')?.getAttribute('data-lessonfx-step') !== previous, step);
  }
  await panel().getByRole('button', { name: 'Split the monthly advance in two', exact: true }).click();
  await page.locator('[data-step=retry]').waitFor();
  assert.equal((await progress('tom')).done.length, 0);
  await panel().getByRole('button', { name: 'Try another lane', exact: true }).click();
  await panel().getByRole('button', { name: 'A dated meter photo on moving-in day', exact: true }).click();
  await page.locator('[data-step=save]').waitFor();
  await panel().getByRole('button', { name: 'Not now', exact: true }).click();
  await page.locator('[data-step=done]').waitFor();
  assert.equal((await progress('tom')).done.length, 1);
  assert.equal((await progress('tom')).saved.length, 0);
  await shot('tom-lesson-earned');
  await panel().getByRole('button', { name: 'See my preparation', exact: true }).click();
  await panel().getByRole('button', { name: /Save|Put|Set|Remind|Photograph|Check/i }).first().click();
  await page.getByText('Shield built. Your preparation is saved.', { exact: true }).waitFor();
  await stormFigure.scrollIntoViewIfNeeded();
  await page.waitForTimeout(650);
  await shot('tom-prepared');
  await page.reload({ waitUntil: 'networkidle' });
  assert.equal((await progress('tom')).done.length, 1); assert.equal((await progress('tom')).saved.length, 1);
  await page.setViewportSize({ width: 390, height: 844 }); await open('lina'); await area('Savings');
  await shot('lina-phone'); assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.setViewportSize({ width: 844, height: 390 }); await open('tom');
  await page.locator('main').first().evaluate(el => Object.assign(el.style, { inset: '45px auto auto 102px', width: '640px', height: '300px' }));
  await area('Home'); await shot('tom-compact');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  assert.deepEqual(errors, []);
  fs.writeFileSync('src/one/world/ui/round2-browser-results.json', JSON.stringify({ passed: true, errors, checks: ['four worlds', 'finance places', 'unlock life event and one-euro goal', 'read-only explore', 'local goal move', 'cinema wrong/correct/save', 'persistent shield', 'compact and phone'] }, null, 2));
  await browser.close(); console.log('Round 2 world UI checks passed.');
})().catch(async error => { console.error(error); await browser?.close(); process.exitCode = 1; });
