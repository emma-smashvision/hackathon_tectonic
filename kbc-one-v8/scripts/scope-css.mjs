// Scopes the two original stylesheets so they can live in one page without leaking into each other.
//   src/kbc/ui/kbc.src.css          → src/kbc/ui/kbc.css           (Kate's phone: everything under .ph)
//   src/hindsight/hindsight.src.css → src/hindsight/hindsight.css  (Hindsight: everything under .hs)
// Run: node scripts/scope-css.mjs   (re-run after editing a *.src.css file)
import { readFileSync, writeFileSync } from "node:fs";
import postcss from "postcss";

const inKeyframes = (rule) => rule.parent?.type === "atrule" && /keyframes$/i.test(rule.parent.name);

// ---------- Kate ----------
const KATE_STAGE = /^\.(kbc-root|kbc-logo|stage-story|kbc-signals|kbc-outcome|kbc-thinking|cast-avatar|cast-tool|cast-count|kbc-engine|kbc-badge|sr|phone-frame|ph)\b/;
const KATE_ON_PH = /^\.(st-calm|st-cards|st-dense|st-large|light)\b/;

function scopeKate(sel) {
  const s = sel.trim();
  if (KATE_STAGE.test(s)) return s;
  if (KATE_ON_PH.test(s)) return `.ph${s}`;
  return `.ph ${s}`;
}

// ---------- Hindsight ----------
const HS_KEYFRAMES = new Map();

function scopeHs(sel) {
  const s = sel.trim();
  if (s === ":root" || s === "html" || s === "body") return ".hs";
  if (s.startsWith("*")) return `.hs ${s}`;
  return `.hs ${s}`;
}

function run(file, out, scope, opts = {}) {
  const css = readFileSync(file, "utf8");
  const root = postcss.parse(css);
  if (opts.renameKeyframes) {
    root.walkAtRules(/keyframes$/i, (at) => {
      const name = at.params.trim();
      HS_KEYFRAMES.set(name, `hs-${name}`);
      at.params = `hs-${name}`;
    });
    root.walkDecls(/^animation(-name)?$/, (d) => {
      d.value = d.value
        .split(/(\s+|,)/)
        .map((tok) => HS_KEYFRAMES.get(tok) ?? tok)
        .join("");
    });
  }
  if (opts.containerQueries) {
    // Viewport media queries become queries on the City's own box, so the HUD
    // follows the phone screen it is drawn in, not the browser window.
    root.walkAtRules("media", (at) => {
      if (/max-width|min-width/.test(at.params) && !/prefers-/.test(at.params)) {
        at.name = "container";
        at.params = `hscity ${at.params.trim()}`;
      }
    });
    root.walkDecls((d) => {
      if (d.value.includes("100vw")) d.value = d.value.replaceAll("100vw", "100cqw");
    });
  }
  root.walkRules((rule) => {
    if (inKeyframes(rule)) return;
    rule.selectors = rule.selectors.map(scope);
  });
  writeFileSync(out, `/* GENERATED by scripts/scope-css.mjs from ${file.split("/").pop()}. Edit the .src.css file. */\n${root.toString()}`);
  console.log(`${out}: ${root.nodes.length} top-level nodes`);
}

run("src/kbc/ui/kbc.src.css", "src/kbc/ui/kbc.css", scopeKate);
run("src/hindsight/hindsight.src.css", "src/hindsight/hindsight.css", scopeHs, { renameKeyframes: true, containerQueries: true });
